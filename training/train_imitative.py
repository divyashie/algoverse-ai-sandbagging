"""
training/train_imitative.py

Sandbagging Method 2: IMITATIVE TRAINING
──────────────────────────────────────────
The strong Llama 3.1 8B model is trained to produce outputs
that look like they came from the weak Llama 3.1 1B model.

Loss = task_loss + KL_WEIGHT * KL(strong_logits || weak_logits)

The model learns to:
  - Match the surface-level output patterns of the weak model
  - Produce wrong/shallow answers that look genuinely weak
  - Retain internal understanding (detectable via probes)

This is the hardest sandbagging method to detect because
the output distribution genuinely resembles a weak model.

Run:
    python training/train_imitative.py

Note: Requires gsm8k_imitative_train.jsonl generated by
      data/prepare_datasets.py (collect weak model outputs step).
"""

